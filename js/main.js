// ===== Ішкі беттер: «Артқа» батырмасы көрінбей кеткенде сол жақ төменде жылтыр нұсқар пайда болады =====
(function () {
  var back = document.querySelector('.cap__head .back');
  if (!back || !('IntersectionObserver' in window)) return;
  var f = document.createElement('a');
  f.className = 'back-float';
  f.href = back.getAttribute('href');
  f.setAttribute('aria-label', back.getAttribute('aria-label') || 'Артқа');
  f.setAttribute('data-i18n-aria', 'back');
  f.innerHTML = back.querySelector('.back__arrow').innerHTML;
  document.body.appendChild(f);
  new IntersectionObserver(function (es) {
    f.classList.toggle('is-on', !es[0].isIntersecting);
  }).observe(back);
})();

