// ===== Тіл ауыстырғыш: таңдалған тіл алтын болады, таңдау есте сақталады. Әдепкі — қазақша =====
(function () {
  var buttons = document.querySelectorAll('.lang button');
  var saved = null;
  try { saved = localStorage.getItem('lang'); } catch (e) {}

  function setLang(lang) {
    var dict = I18N[lang];
    buttons.forEach(function (b) {
      b.setAttribute('aria-pressed', b.dataset.lang === lang ? 'true' : 'false');
    });
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var t = dict[el.dataset.i18n];
      if (t !== undefined) el.textContent = t;   // бос жол да болуы мүмкін (welcome.pre/post)
    });
    document.querySelectorAll('[data-i18n-alt]').forEach(function (el) {
      var t = dict[el.dataset.i18nAlt];
      if (t) el.setAttribute('alt', t);
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
      var t = dict[el.dataset.i18nAria];
      if (t) el.setAttribute('aria-label', t);
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
      var t = dict[el.dataset.i18nPh];
      if (t) el.setAttribute('placeholder', t);
    });
    document.documentElement.lang = lang;
    try { localStorage.setItem('lang', lang); } catch (e) {}
    document.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
  }

  buttons.forEach(function (b) {
    b.addEventListener('click', function () { setLang(b.dataset.lang); });
  });

  setLang(saved === 'ru' || saved === 'en' ? saved : 'kk');
})();

// ===== Мәзір: ашу / жабу =====
(function () {
  var body = document.body;
  var menu = document.getElementById('menu');
  var openBtn = document.querySelector('.menu-btn');
  var closeBtn = menu.querySelector('.menu__close');

  function open() {
    body.classList.add('menu-open');
    menu.removeAttribute('inert');
    menu.setAttribute('aria-hidden', 'false');
    openBtn.setAttribute('aria-expanded', 'true');
    setTimeout(function () { closeBtn.focus(); }, 50);
  }
  function close() {
    body.classList.remove('menu-open');
    menu.setAttribute('inert', '');
    menu.setAttribute('aria-hidden', 'true');
    openBtn.setAttribute('aria-expanded', 'false');
    openBtn.focus();
  }

  openBtn.addEventListener('click', open);
  document.querySelectorAll('[data-menu-close]').forEach(function (el) {
    el.addEventListener('click', close);
  });
  // Пунктті басқанда мәзір жабылады
  menu.querySelectorAll('.menu__list a').forEach(function (a) {
    a.addEventListener('click', close);
  });
  document.addEventListener('keydown', function (e) {
    if (e.key === 'Escape' && body.classList.contains('menu-open')) close();
  });
})();

